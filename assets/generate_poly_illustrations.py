        parts.append(f'<rect x="{cx+5}" y="{cy-11}" width="20" height="15" fill="#E0F7FA" fill-opacity="0.35" stroke="#2D8AA6" stroke-width="3.4"/>')
        parts.append(f'<line x1="{cx-5}" y1="{cy-5}" x2="{cx+5}" y2="{cy-5}" stroke="#2D8AA6" stroke-width="3.4"/>')
