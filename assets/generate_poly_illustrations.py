        rect_poly(cx + 12, cy - 6, 6, 7, "#2D2A32"),
        # Eyebrows
        poly([(cx - 22, cy - 14), (cx - 9, cy - 16), (cx - 9, cy - 12), (cx - 22, cy - 11)], "#4A4148"),
        poly([(cx + 9, cy - 16), (cx + 22, cy - 14), (cx + 22, cy - 11), (cx + 9, cy - 12)], "#4A4148"),
